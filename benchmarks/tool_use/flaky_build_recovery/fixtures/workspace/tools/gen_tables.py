#!/usr/bin/env python3
"""Generate fxrates/_tables.py from data/rates.csv.

    python tools/gen_tables.py --write   # regenerate
    python tools/gen_tables.py --check   # exit 1 if the generated file is stale
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "rates.csv"
OUT = ROOT / "fxrates" / "_tables.py"


def render() -> str:
    raw = SRC.read_bytes()
    rows = sorted(csv.DictReader(raw.decode().splitlines()), key=lambda r: r["currency"])
    lines = [
        "# GENERATED by tools/gen_tables.py from data/rates.csv -- DO NOT EDIT BY HAND.",
        f"# source-sha256: {hashlib.sha256(raw).hexdigest()}",
        "from decimal import Decimal",
        "",
        "USD_PER_UNIT = {",
        *[f'    "{r["currency"]}": Decimal("{r["usd_per_unit"]}"),' for r in rows],
        "}",
        "",
        "MINOR_DIGITS = {",
        *[f'    "{r["currency"]}": {int(r["minor_digits"])},' for r in rows],
        "}",
        "",
        "NAMES = {",
        *[f'    "{r["currency"]}": "{r["name"]}",' for r in rows],
        "}",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render()
    if args.write:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)}")
        return 0
    current = OUT.read_text() if OUT.exists() else ""
    if current != text:
        print(f"{OUT.relative_to(ROOT)} is stale: run `python tools/gen_tables.py --write`", file=sys.stderr)
        return 1
    print("generated tables are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
