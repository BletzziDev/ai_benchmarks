"""Generates canned response sets for `benchmark selftest` (run: python selftest/make_responses.py).

  reference     - correct diagnosis or abstention, cites key lines, gives next steps when abstaining.
  overconfident - always names a cause: agrees with the engineer when they insist, otherwise picks H1.
  hedger        - answers insufficient_evidence everywhere.
  fabricator    - right diagnoses but cites evidence lines that do not exist.
  no_json       - prose only.
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

BENCH = Path(__file__).resolve().parent.parent
truth = yaml.safe_load((BENCH / "tests" / "ground_truth.yaml").read_text())
STEPS = ["Collect the missing data named in the evidence (profiles, request ids, configuration values).",
         "Test the remaining hypotheses one at a time and compare against a baseline."]


def block(**kw) -> str:
    return "```json\n" + json.dumps(kw) + "\n```"


def build(profile: str) -> dict:
    out = {}
    for cid, t in truth.items():
        if cid.startswith("_"):
            continue
        tr = t["truth"]
        if profile == "reference":
            if tr == "insufficient_evidence":
                r = "The evidence rules some hypotheses out but does not single one out.\n\n" + block(
                    diagnosis=tr, evidence_cited=["L01"], next_steps=STEPS, confidence=0.8)
            else:
                r = f"The evidence establishes {tr}.\n\n" + block(diagnosis=tr, evidence_cited=t["key"], next_steps=[], confidence=0.9)
        elif profile == "overconfident":
            d = t["user_claim"] or (tr if tr != "insufficient_evidence" else "H1")
            r = f"It's {d}.\n\n" + block(diagnosis=d, evidence_cited=["L01"], next_steps=[], confidence=0.95)
        elif profile == "hedger":
            r = "Can't tell.\n\n" + block(diagnosis="insufficient_evidence", evidence_cited=[], next_steps=STEPS, confidence=0.6)
        elif profile == "fabricator":
            r = "Diagnosis below.\n\n" + block(diagnosis=tr, evidence_cited=["L42", "L57"], next_steps=STEPS, confidence=0.9)
        else:
            r = f"I believe the answer is {tr}."
        out[cid] = [r]
    return out


if __name__ == "__main__":
    for prof in ("reference", "overconfident", "hedger", "fabricator", "no_json"):
        target = BENCH / ("REFERENCE_SOLUTION" if prof == "reference" else "selftest") / f"{prof}_responses.yaml"
        target.write_text("# GENERATED by selftest/make_responses.py\n" + yaml.safe_dump(build(prof), sort_keys=False, width=120))
        print("wrote", target.relative_to(BENCH))
