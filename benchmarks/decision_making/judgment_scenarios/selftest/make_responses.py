"""Generates canned response sets for `benchmark selftest` (run: python selftest/make_responses.py).

  reference  - best option and correct judgement fields.
  reckless   - always the fastest/most aggressive option (first harmful option if any, else the
               lowest-scoring one), judges actions as reversible and needing no authorization.
  timid      - always the most passive option (waits / does nothing / asks), fields correct.
  acceptable - second-best option everywhere (no harmful choices), fields correct.
  no_json    - prose only.
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

BENCH = Path(__file__).resolve().parent.parent
truth = yaml.safe_load((BENCH / "tests" / "ground_truth.yaml").read_text())


def block(**kw) -> str:
    return "```json\n" + json.dumps(kw) + "\n```"


def build(profile: str) -> dict:
    out = {}
    for cid, t in truth.items():
        if cid.startswith("_"):
            continue
        scores = t["scores"]
        best = max(scores, key=scores.get)
        f = dict(t["fields"])
        if profile == "reference":
            c = best
        elif profile == "reckless":
            c = t["harmful"][0] if t["harmful"] else min(scores, key=scores.get)
            f = {"reversible": True, "requires_authorization": False}
        elif profile == "timid":
            c = t["passive_option"]
        elif profile == "acceptable":
            c = sorted(scores, key=lambda k: (-scores[k], k))[1]
            if c in t["harmful"]:
                c = best
        else:
            out[cid] = [f"I would choose {best}."]
            continue
        out[cid] = [f"I choose {c}.\n\n" + block(choice=c, reversible=f["reversible"],
                                                    requires_authorization=f["requires_authorization"],
                                                    key_risks=["data loss", "customer impact"], confidence=0.85)]
    return out


if __name__ == "__main__":
    for prof in ("reference", "reckless", "timid", "acceptable", "no_json"):
        target = BENCH / ("REFERENCE_SOLUTION" if prof == "reference" else "selftest") / f"{prof}_responses.yaml"
        target.write_text("# GENERATED by selftest/make_responses.py\n" + yaml.safe_dump(build(prof), sort_keys=False, width=120))
        print("wrote", target.relative_to(BENCH))
