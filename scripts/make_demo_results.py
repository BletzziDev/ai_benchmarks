"""Produce the curated demo reports in results/demo/ using the deterministic scripted adapters.

    python scripts/make_demo_results.py [--sandbox local|docker]

Runs `scripted/reference` and `scripted/noop` over every benchmark (1 attempt each), compares them and
copies only the reports (not workspaces) into results/demo/. These are pipeline demonstrations, not
model measurements.
"""

from __future__ import annotations

import argparse
import json
import shutil
import tempfile
from pathlib import Path

from aibench.core.config import load_config
from aibench.core.registry import Registry
from aibench.core.reporting import compare_runs, comparison_markdown, html_report
from aibench.core.runner import Runner

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sandbox", default=None)
    args = ap.parse_args()
    cfg = load_config(ROOT)
    reg = Registry.discover(cfg.benchmarks_dir, set(cfg.suite.categories))
    tmp = Path(tempfile.mkdtemp(prefix="aibench-demo-"))
    runner = Runner(cfg, reg, sandbox_backend=args.sandbox, echo=False, results_dir=tmp)
    stores = []
    for label in ("scripted/reference", "scripted/noop"):
        st = runner.create_run(reg.all(), label, attempts=1, run_id=f"demo-{label.split('/')[1]}")
        runner.execute(st)
        stores.append(st)
    out = ROOT / "results" / "demo"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    for st in stores:
        d = out / st.run_id
        d.mkdir()
        for f in ("manifest.json", "summary.json", "report.md", "report.html"):
            shutil.copy2(st.dir / f, d / f)
    c = compare_runs(stores, cfg)
    (out / "comparison.md").write_text(comparison_markdown(c))
    (out / "comparison.html").write_text(html_report(c["summaries"], c))
    (out / "comparison.json").write_text(json.dumps({k: v for k, v in c.items() if k != "summaries"}, indent=2))
    (out / "README.md").write_text(
        "# Demo results (scripted adapters — NOT model measurements)\n\n"
        "Generated by `python scripts/make_demo_results.py`. `scripted/reference` replays each benchmark's reference\n"
        "solution and `scripted/noop` does nothing; together they show the upper and lower bounds each grader\n"
        "produces and exercise the full pipeline (sandbox, tools, checks, scoring, reports, comparison).\n"
        "Tokens and cost are `n/a` because scripted adapters generate nothing.\n")
    shutil.rmtree(tmp, ignore_errors=True)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
