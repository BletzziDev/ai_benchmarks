"""Result storage layout, run manifests and structured logs.

results/<run_id>/
  manifest.json                 run conditions (model, params, harness, benchmark hashes, sandbox, env)
  run.log.jsonl                 structured log
  attempts/<category>__<name>/a<k>/
      status.json               state machine: running -> completed | infra_error | skipped | interrupted
      prompt.md                 exact rendered task prompt (agent mode)
      transcript.json           neutral message list (and per-case transcripts in chat mode)
      trace.jsonl               every model call / tool call / policy event with timestamps
      final_workspace/          snapshot of the agent workspace (agent mode)
      workspace.diff            unified diff vs the original workspace
      evaluation.json           every check's metrics + evidence
      score.json                criteria, critical failures, score, verdict
      human_grades.json         optional rubric grades entered with `benchmark grade`
      artifacts/                check outputs (test logs, screenshots, ...)
  summary.json                  aggregated results (regenerated by `benchmark report`)
"""

from __future__ import annotations

import json
import os
import platform
import secrets
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from aibench import HARNESS_VERSION
from aibench.core.util import read_json, slug, write_json


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def new_run_id(model_label: str) -> str:
    ts = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    return f"{ts}-{slug(model_label)}-{secrets.token_hex(2)}"


def attempt_key(bench_id: str) -> str:
    return bench_id.replace("/", "__")


class StructuredLog:
    def __init__(self, path: Path | None, echo: bool = True):
        self.path = path
        self.echo = echo
        if path:
            path.parent.mkdir(parents=True, exist_ok=True)

    def _write(self, level: str, event: str, **kw: Any) -> None:
        rec = {"ts": now_iso(), "level": level, "event": event, **kw}
        if self.path:
            with open(self.path, "a", encoding="utf-8") as f:
                f.write(json.dumps(rec, ensure_ascii=False, default=str) + "\n")
        if self.echo and level != "debug":
            extras = " ".join(f"{k}={v}" for k, v in kw.items() if k not in ("traceback",))
            print(f"[{level}] {event} {extras}".rstrip(), file=sys.stderr)

    def info(self, event: str, **kw: Any) -> None:
        self._write("info", event, **kw)

    def warn(self, event: str, **kw: Any) -> None:
        self._write("warning", event, **kw)

    def error(self, event: str, **kw: Any) -> None:
        self._write("error", event, **kw)

    def debug(self, event: str, **kw: Any) -> None:
        self._write("debug", event, **kw)


def git_commit(root: Path) -> dict[str, Any]:
    try:
        sha = subprocess.run(["git", "rev-parse", "HEAD"], cwd=root, capture_output=True, text=True, timeout=10).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain"], cwd=root, capture_output=True, text=True, timeout=10).stdout.strip()
        return {"commit": sha or None, "dirty": bool(dirty)}
    except (OSError, subprocess.SubprocessError):
        return {"commit": None, "dirty": None}


def tool_versions() -> dict[str, Any]:
    out: dict[str, Any] = {"python": sys.version.split()[0], "platform": platform.platform(), "harness": HARNESS_VERSION}
    for mod in ("pytest", "hypothesis", "playwright", "pydantic", "yaml", "anthropic"):
        try:
            m = __import__(mod)
            out[mod] = getattr(m, "__version__", "unknown")
        except Exception:
            out[mod] = None
    try:
        out["docker"] = subprocess.run(["docker", "version", "--format", "{{.Server.Version}}"], capture_output=True,
                                       text=True, timeout=10).stdout.strip() or None
    except (OSError, subprocess.SubprocessError):
        out["docker"] = None
    out["cpu_count"] = os.cpu_count()
    return out


class RunStore:
    def __init__(self, results_dir: Path, run_id: str):
        self.run_id = run_id
        self.dir = Path(results_dir) / run_id
        self.dir.mkdir(parents=True, exist_ok=True)

    @classmethod
    def open(cls, results_dir: Path, run_id: str) -> "RunStore":
        d = Path(results_dir) / run_id
        if not (d / "manifest.json").exists():
            raise FileNotFoundError(f"no run {run_id!r} in {results_dir}")
        return cls(results_dir, run_id)

    @property
    def manifest_path(self) -> Path:
        return self.dir / "manifest.json"

    def manifest(self) -> dict[str, Any]:
        return read_json(self.manifest_path)

    def write_manifest(self, m: dict[str, Any]) -> None:
        write_json(self.manifest_path, m)

    def attempt_dir(self, bench_id: str, k: int) -> Path:
        return self.dir / "attempts" / attempt_key(bench_id) / f"a{k}"

    def status(self, bench_id: str, k: int) -> dict[str, Any] | None:
        p = self.attempt_dir(bench_id, k) / "status.json"
        return read_json(p) if p.exists() else None

    def set_status(self, bench_id: str, k: int, **kw: Any) -> None:
        p = self.attempt_dir(bench_id, k) / "status.json"
        cur = read_json(p) if p.exists() else {}
        cur.update(kw)
        write_json(p, cur)

    def log(self, echo: bool = True) -> StructuredLog:
        return StructuredLog(self.dir / "run.log.jsonl", echo=echo)


def list_runs(results_dir: Path) -> list[dict[str, Any]]:
    runs = []
    if not Path(results_dir).exists():
        return runs
    for d in sorted(Path(results_dir).iterdir()):
        mp = d / "manifest.json"
        if mp.exists():
            try:
                m = read_json(mp)
            except (OSError, json.JSONDecodeError):
                continue
            runs.append({"run_id": d.name, "model": m.get("model", {}).get("label"), "created_at": m.get("created_at"),
                         "state": m.get("state"), "benchmarks": len(m.get("benchmarks", [])), "path": str(d)})
    return runs
